import os
from typing import Dict, Any, List
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

# Lemon Yellow & White Design Palette
LEMON_YELLOW_PRIMARY = "FDE047"    # Lemon Yellow (Tailwind yellow-300)
LEMON_YELLOW_DARK = "CA8A04"       # Deep Lemon Gold (Tailwind yellow-600)
LEMON_YELLOW_LIGHT = "FEFCE8"      # Warm Lemon White (Tailwind yellow-50)
DARK_TEXT = "1E293B"               # Slate 800 for high readability

HEADER_FILL = PatternFill(start_color=LEMON_YELLOW_PRIMARY, end_color=LEMON_YELLOW_PRIMARY, fill_type="solid")
HEADER_FONT = Font(name="Calibri", size=11, bold=True, color=DARK_TEXT)
TITLE_FONT = Font(name="Calibri", size=16, bold=True, color=DARK_TEXT)
SUBTITLE_FONT = Font(name="Calibri", size=10, italic=True, color="854D0E")
SECTION_HEADER_FILL = PatternFill(start_color="FEF08A", end_color="FEF08A", fill_type="solid") # yellow-200
SECTION_HEADER_FONT = Font(name="Calibri", size=11, bold=True, color="713F12")

REGULAR_FONT = Font(name="Calibri", size=10, color="0F172A")
BOLD_FONT = Font(name="Calibri", size=10, bold=True, color="0F172A")

THIN_BORDER = Border(
    left=Side(style="thin", color="FDE68A"), # light amber border
    right=Side(style="thin", color="FDE68A"),
    top=Side(style="thin", color="FDE68A"),
    bottom=Side(style="thin", color="FDE68A")
)

def style_header_row(ws, row_idx: int = 1):
    ws.freeze_panes = f"A{row_idx + 1}"
    for cell in ws[row_idx]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = THIN_BORDER
    ws.row_dimensions[row_idx].height = 28

def autofit_and_format(ws, max_cols: int, start_row: int = 1):
    for col in range(1, max_cols + 1):
        col_letter = get_column_letter(col)
        max_len = 0
        for row in range(start_row, ws.max_row + 1):
            cell = ws.cell(row=row, column=col)
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
            if row > start_row:
                cell.font = REGULAR_FONT
                cell.border = THIN_BORDER
                cell.alignment = Alignment(vertical="center", wrap_text=(len(val_str) > 40))
        
        calculated_width = min(max(max_len + 3, 14), 55)
        ws.column_dimensions[col_letter].width = calculated_width

    last_col_letter = get_column_letter(max_cols)
    ws.auto_filter.ref = f"A{start_row}:{last_col_letter}{ws.max_row}"

def generate_excel_report(analysis_data: Dict[str, Any], output_path: str) -> str:
    wb = openpyxl.Workbook()
    wb.remove(wb.active)

    summary = analysis_data.get("summary", {}) or {}
    pages = analysis_data.get("pages", []) or []
    features = analysis_data.get("features", []) or []
    seo = analysis_data.get("seo", {}) or {}
    technical = analysis_data.get("technical", {}) or {}
    perf = analysis_data.get("performance", {}) or {}
    a11y = analysis_data.get("accessibility", {}) or {}
    adv_draw = analysis_data.get("advantages_drawbacks", {}) or {}
    ai = analysis_data.get("ai", {}) or {}
    contact = analysis_data.get("contact_details", {}) or summary.get("contact_details", {}) or {}

    # ================= SHEET 1: OVERVIEW & CONTACT DETAILS =================
    ws1 = wb.create_sheet(title="Overview")
    ws1.views.sheetView[0].showGridLines = True
    ws1.column_dimensions["A"].width = 26
    ws1.column_dimensions["B"].width = 68

    ws1["A1"] = "WEBSITE AUDIT REPORT"
    ws1["A1"].font = TITLE_FONT
    ws1["A2"] = f"Generated by Website Analyzer on {analysis_data.get('created_at', '')[:10]} (Theme: Lemon Yellow & White)"
    ws1["A2"].font = SUBTITLE_FONT

    overview_rows = [
        ("Target URL", analysis_data.get("url", "")),
        ("Domain Name", analysis_data.get("domain", "")),
        ("Page Title", summary.get("title", "")),
        ("Meta Description", summary.get("meta_description", "")),
        ("Website Category", summary.get("category", "General Web Property")),
        ("Language", summary.get("language", "en")),
        ("Pages Discovered & Crawled", summary.get("pages_count", len(pages))),
        ("Internal Links Discovered", summary.get("internal_links_count", 0)),
        ("External Links Discovered", summary.get("external_links_count", 0)),
        ("HTTPS Enforced", "Yes (Secure TLS)" if analysis_data.get("url", "").startswith("https://") else "No (Insecure HTTP)"),
        ("Crawl Duration", f"{analysis_data.get('crawl_duration', 0)} seconds"),
        ("Analysis Timestamp (UTC)", analysis_data.get("created_at", "")),
        ("Overall SEO Score", f"{analysis_data.get('seo_score', 0)} / 100 ({seo.get('grade', 'N/A')})"),
        ("Performance Score", f"{analysis_data.get('performance_score', 0)} / 100 ({perf.get('grade', 'N/A')})"),
        ("Accessibility Score", f"{analysis_data.get('accessibility_score', 0)} / 100 ({a11y.get('grade', 'N/A')})"),
        ("Detected Technologies", ", ".join([t.get("technology", "") for t in technical.get("technologies", [])]) or "Standard Web Stack")
    ]

    curr_row = 4
    for label, val in overview_rows:
        c1 = ws1.cell(row=curr_row, column=1, value=label)
        c2 = ws1.cell(row=curr_row, column=2, value=val)
        c1.font = BOLD_FONT
        c1.fill = PatternFill(start_color=LEMON_YELLOW_LIGHT, end_color=LEMON_YELLOW_LIGHT, fill_type="solid")
        c1.border = THIN_BORDER
        c2.font = REGULAR_FONT
        c2.border = THIN_BORDER
        c2.alignment = Alignment(wrap_text=True, vertical="center")
        ws1.row_dimensions[curr_row].height = 22
        curr_row += 1

    # CONTACT DETAILS SECTION IN SHEET 1
    curr_row += 1
    ws1.cell(row=curr_row, column=1, value="WEBSITE CONTACT DETAILS")
    ws1.cell(row=curr_row, column=1).font = SECTION_HEADER_FONT
    ws1.cell(row=curr_row, column=1).fill = SECTION_HEADER_FILL
    ws1.cell(row=curr_row, column=2, value="Discovered Public Contact Data")
    ws1.cell(row=curr_row, column=2).font = SECTION_HEADER_FONT
    ws1.cell(row=curr_row, column=2).fill = SECTION_HEADER_FILL
    ws1.row_dimensions[curr_row].height = 24
    curr_row += 1

    emails_str = ", ".join(contact.get("emails", [])) if contact.get("emails") else "None detected during crawl"
    phones_str = ", ".join(contact.get("phone_numbers", [])) if contact.get("phone_numbers") else "None detected during crawl"
    whatsapp_str = ", ".join(contact.get("whatsapp", [])) if contact.get("whatsapp") else "None detected"
    addrs_str = " | ".join(contact.get("addresses", [])) if contact.get("addresses") else "None detected"
    cpages_str = ", ".join(contact.get("contact_pages", [])) if contact.get("contact_pages") else "None detected"
    
    socials = contact.get("social_profiles", {})
    socials_str = ", ".join([f"{k}: {v}" for k, v in socials.items()]) if socials else "None detected"

    contact_rows = [
        ("Public Email Addresses", emails_str),
        ("Phone Numbers", phones_str),
        ("WhatsApp Links", whatsapp_str),
        ("Physical / Postal Address", addrs_str),
        ("Dedicated Contact Pages", cpages_str),
        ("Social Profiles Identified", socials_str)
    ]

    for label, val in contact_rows:
        c1 = ws1.cell(row=curr_row, column=1, value=label)
        c2 = ws1.cell(row=curr_row, column=2, value=val)
        c1.font = BOLD_FONT
        c1.fill = PatternFill(start_color="FEF9C3", end_color="FEF9C3", fill_type="solid") # yellow-100
        c1.border = THIN_BORDER
        c2.font = REGULAR_FONT
        c2.border = THIN_BORDER
        c2.alignment = Alignment(wrap_text=True, vertical="center")
        ws1.row_dimensions[curr_row].height = 22
        curr_row += 1

    # ================= SHEET 2: FEATURES =================
    ws2 = wb.create_sheet(title="Features")
    ws2.views.sheetView[0].showGridLines = True
    headers2 = ["Feature", "Status", "Category", "Confidence", "Detected On", "Evidence"]
    ws2.append(headers2)
    style_header_row(ws2, 1)

    for f in features:
        ws2.append([
            f.get("feature", ""),
            f.get("status", ""),
            f.get("category", ""),
            f.get("confidence", ""),
            f.get("detected_on", ""),
            f.get("evidence", "")
        ])
    autofit_and_format(ws2, len(headers2), 1)

    # ================= SHEET 3: PAGES =================
    ws3 = wb.create_sheet(title="Pages")
    ws3.views.sheetView[0].showGridLines = True
    headers3 = ["Page URL", "Status", "HTTP Code", "Page Title", "H1 Heading", "Word Count", "Internal Links", "External Links", "Images", "Missing ALT"]
    ws3.append(headers3)
    style_header_row(ws3, 1)

    for p in pages:
        ws3.append([
            p.get("url", ""),
            p.get("crawl_status", ""),
            p.get("status_code", ""),
            p.get("title", ""),
            p.get("h1", ""),
            p.get("word_count", 0),
            p.get("internal_links_count", 0),
            p.get("external_links_count", 0),
            p.get("images_count", 0),
            p.get("images_without_alt", 0)
        ])
    autofit_and_format(ws3, len(headers3), 1)

    # ================= SHEET 4: SEO =================
    ws4 = wb.create_sheet(title="SEO")
    ws4.views.sheetView[0].showGridLines = True
    headers4 = ["Check", "Status", "Severity", "Details", "Recommendation"]
    ws4.append(headers4)
    style_header_row(ws4, 1)

    for chk in seo.get("checks", []):
        ws4.append([
            chk.get("check", ""),
            chk.get("status", ""),
            chk.get("severity", ""),
            chk.get("details", ""),
            chk.get("recommendation", "")
        ])
    autofit_and_format(ws4, len(headers4), 1)

    # ================= SHEET 5: TECHNICAL =================
    ws5 = wb.create_sheet(title="Technical")
    ws5.views.sheetView[0].showGridLines = True
    headers5 = ["Technology / Component", "Category", "Detected", "Confidence", "Evidence"]
    ws5.append(headers5)
    style_header_row(ws5, 1)

    for t in technical.get("technologies", []):
        ws5.append([
            t.get("technology", ""),
            t.get("category", ""),
            "Yes" if t.get("detected") else "No",
            t.get("confidence", ""),
            t.get("evidence", "")
        ])
    autofit_and_format(ws5, len(headers5), 1)

    # ================= SHEET 6: PERFORMANCE =================
    ws6 = wb.create_sheet(title="Performance")
    ws6.views.sheetView[0].showGridLines = True
    headers6 = ["Metric", "Measured Value", "Status", "Severity", "Recommendation"]
    ws6.append(headers6)
    style_header_row(ws6, 1)

    for issue in perf.get("issues", []):
        ws6.append([
            issue.get("metric", ""),
            issue.get("value", ""),
            issue.get("status", ""),
            issue.get("severity", ""),
            issue.get("recommendation", "")
        ])
    autofit_and_format(ws6, len(headers6), 1)

    # ================= SHEET 7: ACCESSIBILITY =================
    ws7 = wb.create_sheet(title="Accessibility")
    ws7.views.sheetView[0].showGridLines = True
    headers7 = ["Accessibility Issue", "Severity", "Affected Page", "Evidence", "Recommendation"]
    ws7.append(headers7)
    style_header_row(ws7, 1)

    for a in a11y.get("issues", []):
        ws7.append([
            a.get("issue", ""),
            a.get("severity", ""),
            a.get("affected_page", ""),
            a.get("evidence", ""),
            a.get("recommendation", "")
        ])
    autofit_and_format(ws7, len(headers7), 1)

    # ================= SHEET 8: ADVANTAGES =================
    ws8 = wb.create_sheet(title="Advantages")
    ws8.views.sheetView[0].showGridLines = True
    headers8 = ["Advantage", "Confidence", "Observed Page", "Evidence"]
    ws8.append(headers8)
    style_header_row(ws8, 1)

    for adv in adv_draw.get("advantages", []):
        ws8.append([
            adv.get("advantage", ""),
            adv.get("confidence", ""),
            adv.get("page", ""),
            adv.get("evidence", "")
        ])
    autofit_and_format(ws8, len(headers8), 1)

    # ================= SHEET 9: DRAWBACKS =================
    ws9 = wb.create_sheet(title="Drawbacks")
    ws9.views.sheetView[0].showGridLines = True
    headers9 = ["Issue", "Classification", "Severity", "Affected Page", "Evidence", "Recommendation"]
    ws9.append(headers9)
    style_header_row(ws9, 1)

    for drw in adv_draw.get("drawbacks", []):
        ws9.append([
            drw.get("issue", ""),
            drw.get("classification", ""),
            drw.get("severity", ""),
            drw.get("page", ""),
            drw.get("evidence", ""),
            drw.get("recommendation", "")
        ])
    autofit_and_format(ws9, len(headers9), 1)

    # ================= SHEET 10: RECOMMENDATIONS =================
    ws10 = wb.create_sheet(title="Recommendations")
    ws10.views.sheetView[0].showGridLines = True
    headers10 = ["Priority", "Category", "Recommendation", "Reasoning & Impact"]
    ws10.append(headers10)
    style_header_row(ws10, 1)

    for rec in ai.get("recommendations", []):
        ws10.append([
            rec.get("priority", "Medium"),
            rec.get("category", "General"),
            rec.get("recommendation", ""),
            rec.get("reason", "")
        ])
    autofit_and_format(ws10, len(headers10), 1)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    wb.save(output_path)
    return output_path
